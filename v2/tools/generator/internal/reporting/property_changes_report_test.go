// Test_PropertyChangesReport_GivenTypicalChanges_ShowsExpectedDetails exercises the full range of
// behaviour described by the ADR: a resource with an unchanged status but a modified spec, a
// property rename (LastName -> FamilyName, Nickname -> KnownAs), a new property (LegalName), a
// retired property with no configured rename (FirstName, expected to get a TypoAdvisor suggestion),
// a referenced type rename (Address -> PostalAddress, expected to appear as a Note rather than a
// Modified flag), a wholly new referenced type (CensusData), and a wholly retired referenced type
// (Demographics).
func Test_PropertyChangesReport_GivenTypicalChanges_ShowsExpectedDetails(t *testing.T) {
	t.Parallel()

	golden := goldie.New(t)
	g := gomega.NewWithT(t)

	defs, thisPerson, nextPerson, cfg := createPropertyChangesFixture()

	var content bytes.Buffer
	rpt := reporting.NewPropertyChangesReport(thisPerson, nextPerson, defs, cfg)
	rpt.AddHeader("<!-- // Code generated by azure-service-operator-codegen. DO NOT EDIT. -->")
	g.Expect(rpt.WriteTo(&content)).To(gomega.Succeed())

	golden.Assert(t, t.Name(), content.Bytes())
}

// Test_PropertyChangesReport_GivenNoChanges_ShowsNoModifications confirms that when nothing has
// changed between versions, every row is reported as unmodified and no differential tables appear.
func Test_PropertyChangesReport_GivenNoChanges_ShowsNoModifications(t *testing.T) {
	t.Parallel()

	golden := goldie.New(t)
	g := gomega.NewWithT(t)

	thisSpec := test.CreateSpec(test.Pkg2020, "Person", test.FullNameProperty)
	thisStatus := test.CreateStatus(test.Pkg2020, "Person")
	thisPerson := test.CreateResource(test.Pkg2020, "Person", thisSpec, thisStatus)

	nextSpec := test.CreateSpec(test.Pkg2021, "Person", test.FullNameProperty)
	nextStatus := test.CreateStatus(test.Pkg2021, "Person")
	nextPerson := test.CreateResource(test.Pkg2021, "Person", nextSpec, nextStatus)

	defs := make(astmodel.TypeDefinitionSet)
	defs.AddAll(thisSpec, thisStatus, thisPerson, nextSpec, nextStatus, nextPerson)

	cfg := config.NewObjectModelConfiguration()

	var content bytes.Buffer
	rpt := reporting.NewPropertyChangesReport(thisPerson.Name(), nextPerson.Name(), defs, cfg)
	g.Expect(rpt.WriteTo(&content)).To(gomega.Succeed())

	golden.Assert(t, t.Name(), content.Bytes())
}

func createPropertyChangesFixture() (
	astmodel.TypeDefinitionSet,
	astmodel.InternalTypeName,
	astmodel.InternalTypeName,
	*config.ObjectModelConfiguration,
) {
	thisPkg := test.Pkg2020
	nextPkg := test.Pkg2021

	// v1 (this) referenced types
	thisAddress := test.CreateObjectDefinition(
		thisPkg, "Address",
		astmodel.NewPropertyDefinition("FullAddress", "fullAddress", astmodel.StringType),
		astmodel.NewPropertyDefinition("City", "city", astmodel.StringType))

	thisDemographics := test.CreateObjectDefinition(
		thisPkg, "Demographics",
		astmodel.NewPropertyDefinition("Population", "population", astmodel.IntType))

	thisSpec := test.CreateSpec(
		thisPkg, "Person",
		astmodel.NewPropertyDefinition("BirthDate", "birthDate", astmodel.StringType),
		astmodel.NewPropertyDefinition("FirstName", "firstName", astmodel.StringType),
		astmodel.NewPropertyDefinition("LastName", "lastName", astmodel.StringType),
		astmodel.NewPropertyDefinition("Nickname", "nickname", astmodel.StringType),
		astmodel.NewPropertyDefinition("Residence", "residence", thisAddress.Name()),
		astmodel.NewPropertyDefinition("Stats", "stats", thisDemographics.Name()))

	thisStatus := test.CreateStatus(thisPkg, "Person")

	thisPersonDef := test.CreateResource(thisPkg, "Person", thisSpec, thisStatus)

	// v2 (next) referenced types
	nextPostalAddress := test.CreateObjectDefinition(
		nextPkg, "PostalAddress",
		astmodel.NewPropertyDefinition("FullAddress", "fullAddress", astmodel.StringType),
		astmodel.NewPropertyDefinition("City", "city", astmodel.StringType))

	nextCensusData := test.CreateObjectDefinition(
		nextPkg, "CensusData",
		astmodel.NewPropertyDefinition("Population", "population", astmodel.IntType))

	nextSpec := test.CreateSpec(
		nextPkg, "Person",
		astmodel.NewPropertyDefinition("BirthDate", "birthDate", astmodel.StringType),
		astmodel.NewPropertyDefinition("FamilyName", "familyName", astmodel.StringType),
		astmodel.NewPropertyDefinition("LegalName", "legalName", astmodel.StringType),
		astmodel.NewPropertyDefinition("KnownAs", "knownAs", astmodel.StringType),
		astmodel.NewPropertyDefinition("Residence", "residence", nextPostalAddress.Name()),
		astmodel.NewPropertyDefinition("Census", "census", nextCensusData.Name()))

	nextStatus := test.CreateStatus(nextPkg, "Person")

	nextPersonDef := test.CreateResource(nextPkg, "Person", nextSpec, nextStatus)

	defs := make(astmodel.TypeDefinitionSet)
	defs.AddAll(
		thisAddress, thisDemographics, thisSpec, thisStatus, thisPersonDef,
		nextPostalAddress, nextCensusData, nextSpec, nextStatus, nextPersonDef)

	cfg := config.NewObjectModelConfiguration()

	// Configured type rename: Address -> PostalAddress
	err := cfg.ModifyType(thisAddress.Name(), func(tc *config.TypeConfiguration) error {
		tc.NameInNextVersion.Set("PostalAddress")
		return nil
	})
	if err != nil {
		panic(err)
	}

	// Configured property renames on Person_Spec
	err = cfg.ModifyProperty(thisSpec.Name(), astmodel.PropertyName("LastName"), func(pc *config.PropertyConfiguration) error {
		pc.NameInNextVersion.Set("FamilyName")
		return nil
	})
	if err != nil {
		panic(err)
	}

	err = cfg.ModifyProperty(thisSpec.Name(), astmodel.PropertyName("Nickname"), func(pc *config.PropertyConfiguration) error {
		pc.NameInNextVersion.Set("KnownAs")
		return nil
	})
	if err != nil {
		panic(err)
	}

	return defs, thisPersonDef.Name(), nextPersonDef.Name(), cfg
}
